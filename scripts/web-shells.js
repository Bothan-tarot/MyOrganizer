// Runs after `expo export -p web`.
// Expo exports dynamic routes as files like dist/list/[id].html, but Cloudflare's asset server
// can't serve paths containing brackets (it redirects them to themselves). This copies each
// dynamic route's HTML to a bracket-free path under dist/_shells/ and writes dist/_redirects
// so that e.g. /list/abc is served the /list/[id] page (a 200 rewrite, the URL is kept).
const fs = require('fs');
const path = require('path');

const DIST = path.join(__dirname, '..', 'dist');

function htmlFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) return e.name === '_expo' ? [] : htmlFiles(full);
    return e.name.endsWith('.html') ? [full] : [];
  });
}

const rules = htmlFiles(DIST)
  .map((file) => path.relative(DIST, file).replace(/\\/g, '/').replace(/\.html$/, ''))
  .filter((route) => route.includes('[') && !route.startsWith('+'))
  .map((route) => {
    const segments = route.split('/');
    const pattern = segments
      .map((s) => (s.startsWith('[...') ? '*' : s.replace(/^\[(.+)\]$/, ':$1')))
      .join('/');
    const shell = `_shells/${segments.map((s) => s.replace(/[[\].]/g, '')).join('/')}`;
    fs.mkdirSync(path.dirname(path.join(DIST, shell)), { recursive: true });
    fs.copyFileSync(path.join(DIST, `${route}.html`), path.join(DIST, `${shell}.html`));
    return { pattern: `/${pattern}`, shell: `/${shell}`, depth: segments.length };
  })
  // Only the first matching rule applies: most specific (deepest) routes first, catch-alls last
  .sort((a, b) => b.depth - a.depth || a.pattern.includes('*') - b.pattern.includes('*'));

const lines = ['# Generated by scripts/web-shells.js', ...rules.map((r) => `${r.pattern} ${r.shell} 200`)];
fs.writeFileSync(path.join(DIST, '_redirects'), lines.join('\n') + '\n');
console.log(lines.join('\n'));
